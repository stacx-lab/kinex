"""Generate bundle wrappers, stack scripts and registration documents."""

from pathlib import Path
from shlex import quote

from kinex_ros.bundle_manifest import atomic_write, device_name, render, render_tree, ros_root, write_json

NO_EXTRINSICS = ("model", "detection", "segmentation", "world")
DEFAULT_ACTIONS = {
    "joint": ["read", "write", "stop", "load", "unload", "status", "record_start", "record_stop"],
    "velocity": ["read", "write", "stop", "load", "unload", "status"],
    "rgb": ["read", "load", "unload", "status", "introspect", "record_start", "record_stop"],
    "rgbd": ["read", "load", "unload", "status", "introspect", "record_start", "record_stop"],
    "imu": ["read", "load", "unload", "status"],
    "force_torque": ["read", "load", "unload", "status"],
}


def environment_lines(bundle, facts, workspace=True, here="$HERE"):
    """Bash lines that reproduce the driver environment (shared by ros-python and stack.sh)."""
    ros = bundle.manifest["ros"]
    device = "$DEVICE" if bundle.device_directory != bundle.directory else here
    lines = ["set +u"]
    distro = facts.get("ros_distro")
    if distro:
        lines.append(f"source {quote(f'{ros_root()}/{distro}/setup.bash')}")
    if workspace:
        lines.append(f'[ -f "{device}/ws/install/setup.bash" ] && source "{device}/ws/install/setup.bash"')
    lines.append(f'[ -f "{device}/env.sh" ] && source "{device}/env.sh"')
    lines.append("set -u")
    if "domain_id" in facts:
        lines.append(f"export ROS_DOMAIN_ID={facts['domain_id']}")
    if ros["rmw"]:
        lines.append(f"export RMW_IMPLEMENTATION={ros['rmw']}")
    if ros["rmw"] == "rmw_cyclonedds_cpp":
        lines.append(f'export CYCLONEDDS_URI="file://{here}/cyclonedds.xml"')
    return lines


def render_ros_python(bundle, facts, library, parent=None):
    parent = parent or bundle.parent_directory
    if parent is not None:
        return "\n".join(["#!/usr/bin/env bash", "# Borrow the parent bundle's complete Python environment.",
                          f'exec {quote(str(Path(parent).resolve() / "ros-python"))} "$@"', ""])
    lines = ["#!/usr/bin/env bash", f"# Generated by kinex_ros.bundle for {device_name(bundle, facts)}; do not edit.",
             "set -euo pipefail", 'HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"']
    lines += [f"DEVICE={quote(str(bundle.device_directory.resolve()))}"]
    lines += environment_lines(bundle, facts)
    lines += [f'export PYTHONPATH={quote(str(bundle.target_directory.resolve() / "python") + ":" + library)}"${{PYTHONPATH:+:$PYTHONPATH}}"', f'exec {bundle.manifest["ros"]["python"]} "$@"', ""]
    return "\n".join(lines)


def render_check_sh(bundle):
    return "\n".join(["#!/usr/bin/env bash", "# Generated by kinex_ros.bundle; do not edit.",
                      'HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"', f"DEVICE={quote(str(bundle.device_directory.resolve()))}", 'mkdir -p "$DEVICE/verify"',
                      'exec "$HERE/ros-python" -m kinex_ros.ros2_check --dir "$HERE" --out "$DEVICE/verify/measurements.json" "$@"', ""])


def render_stack_sh(bundle, facts, parent=None):
    parent = parent or bundle.parent_directory
    stack = bundle.manifest["stack"]
    if parent is not None or bundle.manifest["parent"]:
        parent = Path(parent) if parent is not None else bundle.directory.parent / bundle.manifest["parent"]
        return "\n".join(["#!/usr/bin/env bash",
                          f'exec {quote(str(parent.resolve() / "stack.sh"))} "$@"', ""])
    launch = stack["launch"]
    if launch is None:
        start = ['    ready && echo ready || { echo "stack not ready (no launch declared; start it yourself)" >&2; exit 1; }']
        status_gate = ""
    else:
        env = " ".join(f"{key}={quote(render(value, facts))}" for key, value in stack["env"].items())
        args = render(launch["args"], facts).strip()
        command = " ".join(part for part in ("env", env, "ros2 launch", launch["package"], launch["file"], args) if part)
        start = ["    if alive; then", '        echo "running (pid $(cat "$PIDFILE"))"', "    else", '        : > "$LOG"',
                 f'        setsid nohup {command} > "$LOG" 2>&1 &', '        echo $! > "$PIDFILE"', "    fi",
                 '    if ready; then echo ready; else tail -n 30 "$LOG"; exit 1; fi']
        status_gate = '    alive || { echo "not running"; exit 1; }\n'
    lines = ["#!/usr/bin/env bash", f"# Generated by kinex_ros.bundle for {device_name(bundle, facts)}; do not edit.",
             "# Borrowed ROS stack: drivers never start or stop it.", "set -eo pipefail",
             'HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"', f"DEVICE={quote(str(bundle.device_directory.resolve()))}", 'cd "$DEVICE"', "mkdir -p run",
             "PIDFILE=run/stack.pid", "LOG=run/stack.log", f"STOP_SIGNAL={stack['stop']['signal']}",
             f"STOP_TIMEOUT={int(stack['stop']['timeout_s'])}", ""]
    lines += environment_lines(bundle, facts) + ["", """alive() {
    [ -f "$PIDFILE" ] || return 1
    local pid
    pid="$(cat "$PIDFILE")"
    [ -n "$pid" ] && kill -0 -- "-$pid" 2>/dev/null
}

ready() {
    "$HERE/ros-python" -m kinex_ros.ros2_check --dir "$HERE" --ready "$@"
}

wait_gone() {
    local ticks=$(( $1 * 10 ))
    while [ "$ticks" -gt 0 ]; do
        alive || return 0
        sleep 0.1
        ticks=$((ticks - 1))
    done
    ! alive
}

start() {
""" + "\n".join(start) + """
}

stop() {
    if ! alive; then
        rm -f "$PIDFILE"
        echo "not running"
        return
    fi
    local pid
    pid="$(cat "$PIDFILE")"
    kill -"$STOP_SIGNAL" -- "-$pid" 2>/dev/null || true
    if ! wait_gone "$STOP_TIMEOUT"; then
        kill -TERM -- "-$pid" 2>/dev/null || true
        if ! wait_gone 5; then
            kill -KILL -- "-$pid" 2>/dev/null || true
            wait_gone 2 || true
        fi
    fi
    rm -f "$PIDFILE"
    echo stopped
}

status() {
""" + status_gate + """    if ready --timeout-s 1 > /dev/null 2>&1; then echo ready; else echo "running, not ready"; exit 2; fi
}

case "${1:-}" in
    start) start ;;
    stop) stop ;;
    status) status ;;
    logs) tail -n 50 "$LOG" ;;
    *) echo "usage: stack.sh start|stop|status|logs" >&2; exit 64 ;;
esac
"""]
    return "\n".join(lines)


def render_cyclonedds_xml(facts):
    interface = facts.get("network_interface")
    interfaces = (f'      <Interfaces><NetworkInterface name="{interface}" priority="default" multicast="default"/></Interfaces>\n'
                  if interface else "")
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<CycloneDDS xmlns="https://cdds.io/config">\n  <Domain Id="any">\n'
            f"    <General>\n{interfaces}      <AllowMulticast>default</AllowMulticast>\n    </General>\n  </Domain>\n</CycloneDDS>\n")


def _ros_connection(bundle, facts):
    driver = bundle.manifest["driver"]
    connection = {"kind": "ros"}
    kind = bundle.type
    keys = (("state_topic", "command_topic") if kind in ("joint", "velocity") else
            ("color_topic", "depth_topic") if kind in ("rgb", "rgbd") else ("state_topic",))
    for key in keys:
        if key in driver:
            connection[key] = render(driver[key], facts)
    return connection


def render_profile(bundle, facts, interpreter=None):
    """The complete, unloaded device profile for ``profile_write``."""
    manifest = bundle.manifest
    access = manifest["profile"]["access"]
    driver = manifest["driver"]
    connection = render_tree(access["connection"], facts) if "connection" in access else _ros_connection(bundle, facts)
    if interpreter is None:
        interpreter = render(access["driver"]["interpreter"], facts) if "interpreter" in access.get("driver", {}) \
            else str(bundle.target_directory.resolve() / "ros-python")
    profile = {
        "name": device_name(bundle, facts), "type": bundle.type, "loaded": False,
        "access": {"source": "default", "connection": connection,
                   "driver": {"entry": str((bundle.target_directory / "driver.py").relative_to(bundle.device_directory)), "interpreter": interpreter,
                              "actions": list(driver.get("actions") or DEFAULT_ACTIONS.get(bundle.type, ["read", "load", "unload", "status"])),
                              "persistent": True, "timeout_s": driver.get("timeout_s", 30)}},
        "intrinsics": {"source": "default", **render_tree(manifest["profile"]["intrinsics"], facts)},
    }
    if bundle.type not in NO_EXTRINSICS:
        profile["extrinsics"] = {"source": "default", **render_tree(manifest["profile"]["extrinsics"], facts)}
    model = profile["intrinsics"].get("model", {})
    if model.get("format") == "urdf" and isinstance(model.get("path"), str):
        model_path = Path(model["path"])
        if not model_path.is_absolute() and (bundle.directory / model_path).is_file():
            model["path"] = str((bundle.target_directory / model_path).relative_to(bundle.device_directory))
    return profile


def render_robot(bundle, facts):
    robot = bundle.manifest["robot"]
    if robot is None:
        return None
    name = device_name(bundle, facts)
    model = facts.get(robot["model_fact"]) if robot["model_fact"] else (render(robot["model"], facts) if robot["model"] else None)
    identity = {"id": name, "name": name, "platform": "real", "kind": robot["kind"]}
    if model is not None:
        identity["model"] = model
    return {"identity": identity}


def render_recipe(bundle, facts):
    recipe = bundle.manifest["recipe"]
    if recipe is None:
        return None
    return {"version": 1, "nodes": render_tree(recipe["nodes"], facts), "task": render_tree(recipe["task"], facts)}


def write_scripts(bundle, facts, library, parent=None):
    """ros-python, stack.sh, check.sh and cyclonedds.xml; returns the written names."""
    directory = bundle.directory
    if parent is None and bundle.manifest["parent"]:
        parent = directory.parent / bundle.manifest["parent"]
    written = ["ros-python", "check.sh"]
    atomic_write(directory / "ros-python", render_ros_python(bundle, facts, library, parent), executable=True)
    atomic_write(directory / "check.sh", render_check_sh(bundle), executable=True)
    if bundle.manifest["stack"] is not None or parent is not None:
        atomic_write(directory / "stack.sh", render_stack_sh(bundle, facts, parent), executable=True)
        written.append("stack.sh")
    if bundle.manifest["ros"]["rmw"] == "rmw_cyclonedds_cpp":
        atomic_write(directory / "cyclonedds.xml", render_cyclonedds_xml(facts))
        written.append("cyclonedds.xml")
    return written


def write_profile(bundle, facts, interpreter=None):
    """profile.generated.json, robot.generated.json and recipe.json; returns the written names."""
    directory = bundle.directory
    written = ["profile.generated.json"]
    write_json(directory / "profile.generated.json", render_profile(bundle, facts, interpreter))
    robot = render_robot(bundle, facts)
    if robot is not None:
        write_json(directory / "robot.generated.json", robot)
        written.append("robot.generated.json")
    recipe = render_recipe(bundle, facts)
    if recipe is not None:
        write_json(directory / "recipe.json", recipe)
        written.append("recipe.json")
    return written
